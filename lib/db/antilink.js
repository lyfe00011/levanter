exports.setSubscription = async (w, x = "0", y = true) => {
  const B = {
    chat: w,
    session: x,
  };
  const C = {
    where: B,
  };
  const D = await subscriptionDB.findOne(C);
  const E = new Date();
  E.setDate(E.getDate() + 30);
  const F = E.toLocaleDateString("en-GB");
  const G = {
    chat: w,
    message: F,
    session: x,
  };
  const H = {
    chat: w,
  };
  H.session = x;
  H.message = F;
  return D
    ? (await D.update(G)).message
    : (await subscriptionDB.create(H)).message;
};
